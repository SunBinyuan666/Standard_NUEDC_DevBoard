#ifndef APP_SERVO_H
#define APP_SERVO_H

#include "stm32f1xx_hal.h"

#define SERVO_MIN_ANGLE_DEG      0U     /* 目标角度下限(度) */
#define SERVO_MAX_ANGLE_DEG    180U     /* 目标角度上限(度) */
#define SERVO_MIN_PULSE_US   1150U     /* 下限脉宽(us), 端点嗡鸣后收窄 */
#define SERVO_MAX_PULSE_US   1850U     /* 上限脉宽(us), 端点嗡鸣后收窄 */
#define SERVO_DEFAULT_ANGLE   90U     /* 上电默认目标角度(度) */

/*************************************
 * 函数名称 ： app_servo_init
 * 描述     ： 舵机模块初始化, 启动TIM3_CH1 PWM并输出
 *             默认角度(90度, 约1500us中位脉冲)
 * 输入     ： 无
 * 输出     ： 无
 * 返回     ： 无
 **************************************/
void app_servo_init(void);

/*************************************
 * 函数名称 ： app_servo_set_angle
 * 描述     ： 设定目标角度: 先限幅到0~180度(防无符号下溢),
 *             再线性换算为脉宽并更新TIM3_CH1比较值
 * 输入     ： angle_deg - 目标角度(度), 超范围自动饱和
 * 输出     ： 无
 * 返回     ： 无
 **************************************/
void app_servo_set_angle(uint16_t angle_deg);

/*************************************
 * 函数名称 ： app_servo_get_angle
 * 描述     ： 读取当前目标角度(已限幅后的实际设定值)
 * 输入     ： 无
 * 输出     ： 无
 * 返回     ： 当前目标角度(度)
 **************************************/
uint16_t app_servo_get_angle(void);

#endif /* APP_SERVO_H */
